/// [bucket] zaman dilimine göre söz havuzunu döner — [locale] için ilgili
/// liste boşsa (henüz doldurulmadıysa) Türkçe'ye düşer (bkz. dosya üstü not).
List<String> timeBucketQuotes(TimeBucket bucket, Locale locale) {
  final tr = switch (bucket) {
    TimeBucket.morning => motivationMorningTr,
    TimeBucket.afternoon => motivationAfternoonTr,
    TimeBucket.evening => motivationEveningTr,
    TimeBucket.night => motivationNightTr,
  };
  final localized = switch (locale.languageCode) {
    'en' => switch (bucket) {
      TimeBucket.morning => motivationMorningEn,
      TimeBucket.afternoon => motivationAfternoonEn,
      TimeBucket.evening => motivationEveningEn,
      TimeBucket.night => motivationNightEn,
    },
    'es' => switch (bucket) {
      TimeBucket.morning => motivationMorningEs,
      TimeBucket.afternoon => motivationAfternoonEs,
      TimeBucket.evening => motivationEveningEs,
      TimeBucket.night => motivationNightEs,
    },
    _ => tr,
  };
  return localized.isEmpty ? tr : localized;
}

