/// [id]'ye karşılık gelen temayı bulur; bulunamazsa `null` döner (ör.
/// aktif id'nin listeden kaldırılmış olması gibi olmayacak ama savunmacı
/// bir durum — `findCostumeById` ile aynı desen).
